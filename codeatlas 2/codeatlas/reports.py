"""Markdown project report generation."""
from __future__ import annotations

from .analysis import riskiest_functions
from .graph import CallGraph, module_dependencies
from .llm import Summarizer
from .parser import Project


def generate_report(project: Project, graph: CallGraph,
                    summarizer: Summarizer | None = None) -> str:
    summarizer = summarizer or Summarizer()
    L: list[str] = []

    L.append(f"# CodeAtlas Report - {project.name}")
    L.append("")
    L.append("## 1. Application Overview")
    L.append("")
    L.append(summarizer.project_overview(project))
    L.append("")

    n_func = len(project.all_functions())
    n_cls = sum(len(m.classes) for m in project.modules)
    total_loc = sum(m.loc for m in project.modules)
    L.append("## 2. Project Statistics")
    L.append("")
    L.append(f"- Modules: {len(project.modules)}")
    L.append(f"- Functions: {n_func}")
    L.append(f"- Classes: {n_cls}")
    L.append(f"- Lines of code: {total_loc}")
    L.append("")

    L.append("## 3. Module Breakdown")
    L.append("")
    L.append("| Module | File | Functions | Classes | LOC |")
    L.append("|---|---|---|---|---|")
    for m in project.modules:
        L.append(f"| `{m.dotted_name}` | `{m.path}` | {len(m.functions)} "
                 f"| {len(m.classes)} | {m.loc} |")
    L.append("")

    L.append("## 4. Module Dependencies")
    L.append("")
    deps = module_dependencies(project)
    if deps:
        for mod, ds in deps.items():
            L.append(f"- `{mod}` -> {', '.join(f'`{d}`' for d in ds)}")
    else:
        L.append("No inter-module dependencies detected.")
    L.append("")

    L.append("## 5. Risk Analysis - Riskiest Functions")
    L.append("")
    L.append("| Function | Location | Risk | Score | Complexity | LOC |")
    L.append("|---|---|---|---|---|---|")
    for f in riskiest_functions(project, 15):
        L.append(f"| `{f.qualified_name}` | `{f.file}:{f.lineno}` | "
                 f"**{f.risk_level}** | {f.risk_score} | {f.complexity} | {f.loc} |")
    L.append("")

    L.append("## 6. Function Optimality Notes")
    L.append("")
    flagged = [f for f in project.all_functions() if f.suggestions]
    flagged.sort(key=lambda f: -f.risk_score)
    if flagged:
        for f in flagged[:15]:
            L.append(f"### `{f.qualified_name}` (`{f.file}:{f.lineno}`)")
            for s in f.suggestions:
                L.append(f"- {s}")
            L.append("")
    else:
        L.append("No optimality concerns flagged.")
        L.append("")

    L.append("## 7. Entry Points")
    L.append("")
    for q in graph.entry_points(15):
        fn = graph.nodes[q]
        L.append(f"- `{q}` (`{fn.file}:{fn.lineno}`)")
    L.append("")
    L.append("---")
    L.append("*Generated by CodeAtlas - AI Codebase Investigator*")
    return "\n".join(L)
